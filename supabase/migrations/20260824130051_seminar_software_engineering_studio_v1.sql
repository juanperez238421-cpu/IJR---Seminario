create table if not exists public.seminar_studio_profiles (
  id uuid primary key default gen_random_uuid(),
  response_id uuid not null unique default gen_random_uuid(),
  edit_token_hash text not null unique,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  last_student_activity_at timestamptz not null default clock_timestamp(),
  teacher_updated_at timestamptz,
  full_name text not null check (char_length(trim(full_name)) between 3 and 140),
  group_code text not null check (group_code in ('11-A','11-B','11-C')),
  topics text[] not null,
  first_choice text not null,
  track_slug text not null check (track_slug in ('web','data-science','cybersecurity','3d-programming','robotics')),
  work_mode text not null check (work_mode in ('Individual','Pareja')),
  partner_name text,
  project_idea text,
  project_title text,
  repo_full_name text,
  uml_url text,
  sprint_current smallint not null default 1 check (sprint_current between 1 and 8),
  progress_percent smallint not null default 0 check (progress_percent between 0 and 100),
  next_goal text,
  status text not null default 'active' check (status in ('active','complete','paused')),
  teacher_note text,
  constraint seminar_studio_topics_count check (cardinality(topics) between 1 and 5),
  constraint seminar_studio_first_choice check (first_choice = any(topics)),
  constraint seminar_studio_partner check ((work_mode='Individual' and partner_name is null) or (work_mode='Pareja' and char_length(trim(coalesce(partner_name,''))) between 3 and 140)),
  constraint seminar_studio_repo_format check (repo_full_name is null or repo_full_name ~ '^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$')
);
comment on table public.seminar_studio_profiles is 'Private student route/profile state for Seminar 11 Software Engineering Studio. Browser clients have no direct table access; student writes/reads go through the constrained Edge Function and teacher reads/updates through the MFA gateway.';
create index if not exists seminar_studio_profiles_group_idx on public.seminar_studio_profiles(group_code,full_name);
create index if not exists seminar_studio_profiles_track_idx on public.seminar_studio_profiles(track_slug,sprint_current);
create index if not exists seminar_studio_profiles_activity_idx on public.seminar_studio_profiles(last_student_activity_at desc);
alter table public.seminar_studio_profiles enable row level security;
revoke all on table public.seminar_studio_profiles from public,anon,authenticated;
grant select,insert,update on table public.seminar_studio_profiles to service_role;

create table if not exists public.seminar_studio_events (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default clock_timestamp(),
  profile_id uuid references public.seminar_studio_profiles(id) on delete cascade,
  event_type text not null check (event_type in ('register','load','student_update','teacher_update')),
  payload jsonb not null default '{}'::jsonb,
  ip_hash text,
  user_agent text
);
comment on table public.seminar_studio_events is 'Private audit trail for Seminar 11 Studio profile lifecycle. No direct browser access.';
create index if not exists seminar_studio_events_profile_idx on public.seminar_studio_events(profile_id,occurred_at desc);
alter table public.seminar_studio_events enable row level security;
revoke all on table public.seminar_studio_events from public,anon,authenticated;
grant select,insert on table public.seminar_studio_events to service_role;

